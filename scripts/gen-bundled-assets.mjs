#!/usr/bin/env node
// Inlines each package's `templates/` tree into a TypeScript module.
//
// The standalone binary has no filesystem to read those templates back from
// (`import.meta.dirname` points inside the compiled bundle), so they are
// resolved from an embedded map instead of from disk in every build.

import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PACKAGES = ['cli', 'runner'];

async function walk(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(full)));
    else out.push(full);
  }
  return out;
}

for (const pkg of PACKAGES) {
  const templatesDir = join(ROOT, pkg, 'templates');
  const files = (await walk(templatesDir)).sort();

  const entries = [];
  for (const file of files) {
    const key = relative(templatesDir, file).split('\\').join('/');
    entries.push(`  ${JSON.stringify(key)}: ${JSON.stringify(await readFile(file, 'utf-8'))},`);
  }

  const { version } = JSON.parse(await readFile(join(ROOT, pkg, 'package.json'), 'utf-8'));

  const source = [
    '// Generated by scripts/gen-bundled-assets.mjs — do not edit.',
    '',
    `export const PACKAGE_VERSION = ${JSON.stringify(version)};`,
    '',
    `/** Contents of ${pkg}/templates/, keyed by path relative to that directory. */`,
    'export const BUNDLED_ASSETS: Record<string, string> = {',
    ...entries,
    '};',
    '',
  ].join('\n');

  const outFile = join(ROOT, pkg, 'src', 'generated', 'bundled-assets.ts');
  await mkdir(dirname(outFile), { recursive: true });
  await writeFile(outFile, source, 'utf-8');
  console.log(`${relative(ROOT, outFile)} — ${files.length} files`);
}
